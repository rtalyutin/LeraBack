
CREATE TABLE IF NOT EXISTS __APP_SCHEMA__.schema_migrations (
    version INTEGER PRIMARY KEY,
    applied_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS __APP_SCHEMA__.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes BETWEEN 1 AND 1440),
    active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1))
);
CREATE TABLE IF NOT EXISTS __APP_SCHEMA__.masters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1))
);
CREATE TABLE IF NOT EXISTS __APP_SCHEMA__.rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1))
);
CREATE TABLE IF NOT EXISTS __APP_SCHEMA__.master_services (
    master_id BIGINT NOT NULL REFERENCES __APP_SCHEMA__.masters(id),
    service_id BIGINT NOT NULL REFERENCES __APP_SCHEMA__.services(id),
    PRIMARY KEY (master_id, service_id)
);
CREATE TABLE IF NOT EXISTS __APP_SCHEMA__.room_services (
    room_id BIGINT NOT NULL REFERENCES __APP_SCHEMA__.rooms(id),
    service_id BIGINT NOT NULL REFERENCES __APP_SCHEMA__.services(id),
    PRIMARY KEY (room_id, service_id)
);

-- weekday: Monday=0. Date-specific open intervals replace weekly opens for that date.
-- Date-specific closed intervals always subtract from opens.
CREATE TABLE IF NOT EXISTS __APP_SCHEMA__.work_intervals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    master_id BIGINT REFERENCES __APP_SCHEMA__.masters(id),
    room_id BIGINT REFERENCES __APP_SCHEMA__.rooms(id),
    weekday INTEGER CHECK (weekday BETWEEN 0 AND 6),
    local_date TEXT,
    mode TEXT NOT NULL CHECK (mode IN ('open', 'closed')),
    start_minute INTEGER NOT NULL CHECK (start_minute BETWEEN 0 AND 1439),
    end_minute INTEGER NOT NULL CHECK (end_minute BETWEEN 1 AND 1440),
    CHECK ((master_id IS NOT NULL) != (room_id IS NOT NULL)),
    CHECK ((weekday IS NOT NULL) != (local_date IS NOT NULL)),
    CHECK (start_minute < end_minute)
);
CREATE INDEX IF NOT EXISTS work_master_day ON __APP_SCHEMA__.work_intervals(master_id, local_date, weekday);
CREATE INDEX IF NOT EXISTS work_room_day ON __APP_SCHEMA__.work_intervals(room_id, local_date, weekday);

CREATE TABLE IF NOT EXISTS __APP_SCHEMA__.resource_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    master_id BIGINT REFERENCES __APP_SCHEMA__.masters(id),
    room_id BIGINT REFERENCES __APP_SCHEMA__.rooms(id),
    start_utc TEXT NOT NULL,
    end_utc TEXT NOT NULL,
    reason TEXT,
    created_by TEXT NOT NULL,
    CHECK ((master_id IS NOT NULL) != (room_id IS NOT NULL)),
    CHECK (start_utc < end_utc)
);
CREATE INDEX IF NOT EXISTS blocks_master_time ON __APP_SCHEMA__.resource_blocks(master_id, start_utc, end_utc);
CREATE INDEX IF NOT EXISTS blocks_room_time ON __APP_SCHEMA__.resource_blocks(room_id, start_utc, end_utc);

CREATE TABLE IF NOT EXISTS __APP_SCHEMA__.clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vk_id BIGINT UNIQUE,
    phone TEXT NOT NULL,
    phone_provided_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS __APP_SCHEMA__.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT REFERENCES __APP_SCHEMA__.clients(id),
    service_id BIGINT NOT NULL REFERENCES __APP_SCHEMA__.services(id),
    master_id BIGINT NOT NULL REFERENCES __APP_SCHEMA__.masters(id),
    room_id BIGINT NOT NULL REFERENCES __APP_SCHEMA__.rooms(id),
    start_utc TEXT NOT NULL,
    end_utc TEXT NOT NULL,
    source TEXT NOT NULL CHECK (source IN ('vk', 'admin')),
    status TEXT NOT NULL CHECK (status IN ('confirmed', 'cancelled', 'rescheduled')),
    phone_snapshot TEXT NOT NULL,
    service_name_snapshot TEXT NOT NULL,
    master_name_snapshot TEXT NOT NULL,
    prior_booking_id BIGINT REFERENCES __APP_SCHEMA__.bookings(id),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    CHECK (start_utc < end_utc)
);
CREATE INDEX IF NOT EXISTS bookings_master_time ON __APP_SCHEMA__.bookings(master_id, start_utc, end_utc) WHERE status='confirmed';
CREATE INDEX IF NOT EXISTS bookings_room_time ON __APP_SCHEMA__.bookings(room_id, start_utc, end_utc) WHERE status='confirmed';
CREATE INDEX IF NOT EXISTS bookings_client ON __APP_SCHEMA__.bookings(client_id, status, start_utc);

