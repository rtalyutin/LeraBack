-- Direct consumers must share the same lock as the booking service. The trigger
-- serializes even a writer that bypasses the service and rejects overlaps.
CREATE OR REPLACE FUNCTION __APP_SCHEMA__.protect_booking_overlap() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
BEGIN
    IF NEW.status = 'confirmed' THEN
        PERFORM pg_advisory_xact_lock(706547229101);
        IF EXISTS (
            SELECT 1 FROM __APP_SCHEMA__.bookings b
            WHERE b.status = 'confirmed' AND b.id IS DISTINCT FROM NEW.id
              AND b.start_utc < NEW.end_utc AND b.end_utc > NEW.start_utc
              AND (b.master_id = NEW.master_id OR b.room_id = NEW.room_id
                   OR (NEW.client_id IS NOT NULL AND b.client_id = NEW.client_id)
                   OR b.phone_snapshot = NEW.phone_snapshot)
        ) THEN
            RAISE EXCEPTION 'booking overlap' USING ERRCODE = '23505';
        END IF;
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS booking_overlap_guard ON __APP_SCHEMA__.bookings;
CREATE TRIGGER booking_overlap_guard BEFORE INSERT OR UPDATE OF master_id,room_id,client_id,
    phone_snapshot,start_utc,end_utc,status ON __APP_SCHEMA__.bookings
    FOR EACH ROW EXECUTE FUNCTION __APP_SCHEMA__.protect_booking_overlap();
