CREATE OR REPLACE FUNCTION __APP_SCHEMA__.current_salon_id() RETURNS bigint
LANGUAGE sql STABLE SET search_path = pg_catalog AS $$
 SELECT CASE WHEN current_setting('app.salon_id', true) ~ '^[1-9][0-9]{0,17}$'
             THEN current_setting('app.salon_id', true)::bigint ELSE NULL END
$$;

