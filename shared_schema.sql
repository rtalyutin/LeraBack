LANGUAGE plpgsql SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
BEGIN
 IF NEW.value_string IS NOT NULL AND EXISTS(SELECT 1 FROM __APP_SCHEMA__.entity_parameters p
  JOIN __APP_SCHEMA__.entity_types t ON t.salon_id=p.salon_id AND t.id=p.entity_type_id
