CREATE OR REPLACE FUNCTION __APP_SCHEMA__.initialize_salon_metadata() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
DECLARE template record; param jsonb; typ bigint; ref_typ bigint; pid bigint; eid bigint;
 dtype text; val jsonb; policy jsonb; previous_scope text;
BEGIN
 previous_scope:=current_setting('app.salon_id',true);
 PERFORM set_config('app.salon_id',NEW.id::text,true);
 policy:=COALESCE(NULLIF(current_setting('app.provision_policy',true),'')::jsonb,'{}'::jsonb);
 FOR template IN SELECT * FROM __APP_SCHEMA__.core_entity_templates ORDER BY code LOOP
  INSERT INTO __APP_SCHEMA__.entity_types(salon_id,code,label,core,projection_table)
   VALUES(NEW.id,template.code,template.label,true,template.projection_table);
 END LOOP;
 FOR template IN SELECT * FROM __APP_SCHEMA__.core_entity_templates ORDER BY code LOOP
  SELECT id INTO STRICT typ FROM __APP_SCHEMA__.entity_types WHERE salon_id=NEW.id AND code=template.code;
  FOR param IN SELECT * FROM jsonb_array_elements(template.parameters) LOOP
   ref_typ:=NULL;
   IF param->>'reference_code' IS NOT NULL THEN
    SELECT id INTO STRICT ref_typ FROM __APP_SCHEMA__.entity_types WHERE salon_id=NEW.id AND code=param->>'reference_code';
   END IF;
   INSERT INTO __APP_SCHEMA__.entity_parameters(salon_id,entity_type_id,code,label,data_type,required,core,reference_type_id,reference_key)
   VALUES(NEW.id,typ,param->>'code',param->>'label',param->>'data_type',
    (param->>'required')::boolean,true,ref_typ,COALESCE(param->>'reference_key','id'));
  END LOOP;
  IF template.code='salon_settings' THEN
   INSERT INTO __APP_SCHEMA__.entities(salon_id,entity_type_id,projection_key)
    VALUES(NEW.id,typ,jsonb_build_object('id',NEW.id)) RETURNING id INTO eid;
   FOR param IN SELECT * FROM jsonb_array_elements(template.parameters) LOOP
    SELECT id,data_type INTO STRICT pid,dtype FROM __APP_SCHEMA__.entity_parameters
     WHERE salon_id=NEW.id AND entity_type_id=typ AND code=param->>'code';
    val:=COALESCE(policy->(param->>'code'),template.defaults->(param->>'code'));
    IF param->>'code'='name' THEN val:=to_jsonb(NEW.name); END IF;
    INSERT INTO __APP_SCHEMA__.entity_parameter_values(salon_id,entity_id,parameter_id,entity_type_id,
     value_string,value_integer,value_boolean)
    VALUES(NEW.id,eid,pid,typ,
     CASE WHEN dtype='string' THEN val#>>'{}' END,
     CASE WHEN dtype='integer' THEN (val#>>'{}')::bigint END,
     CASE WHEN dtype='boolean' THEN (val#>>'{}')::boolean END);
   END LOOP;
   UPDATE __APP_SCHEMA__.salons SET entity_id=eid WHERE id=NEW.id;
  END IF;
 END LOOP;
 PERFORM set_config('app.salon_id',COALESCE(previous_scope,''),true);
 RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION __APP_SCHEMA__.sync_projection_values() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
DECLARE p __APP_SCHEMA__.entity_parameters; row_data jsonb; v jsonb; ref_id bigint;
BEGIN
 IF TG_OP='DELETE' THEN
  DELETE FROM __APP_SCHEMA__.entities WHERE salon_id=OLD.salon_id AND id=OLD.entity_id;
  RETURN OLD;
 END IF;
 row_data:=to_jsonb(NEW);
 FOR p IN SELECT * FROM __APP_SCHEMA__.entity_parameters WHERE salon_id=NEW.salon_id
  AND entity_type_id=(SELECT entity_type_id FROM __APP_SCHEMA__.entities WHERE salon_id=NEW.salon_id AND id=NEW.entity_id)
  AND core LOOP
  v:=row_data->p.code;
  IF v IS NULL OR v='null'::jsonb THEN
   DELETE FROM __APP_SCHEMA__.entity_parameter_values WHERE salon_id=NEW.salon_id AND entity_id=NEW.entity_id AND parameter_id=p.id;
  ELSE
   ref_id:=NULL;
   IF p.data_type='reference' THEN
    SELECT id INTO STRICT ref_id FROM __APP_SCHEMA__.entities WHERE salon_id=NEW.salon_id
     AND entity_type_id=p.reference_type_id AND projection_key=jsonb_build_object(p.reference_key,v);
   END IF;
   INSERT INTO __APP_SCHEMA__.entity_parameter_values(salon_id,entity_id,parameter_id,entity_type_id,
     value_string,value_integer,value_number,value_boolean,value_date,value_reference)
   VALUES(NEW.salon_id,NEW.entity_id,p.id,p.entity_type_id,
     CASE WHEN p.data_type='string' THEN v#>>'{}' END,
     CASE WHEN p.data_type='integer' THEN (v#>>'{}')::bigint END,
     CASE WHEN p.data_type='number' THEN (v#>>'{}')::numeric END,
     CASE WHEN p.data_type='boolean' THEN (v#>>'{}')::boolean END,
     CASE WHEN p.data_type='date' THEN (v#>>'{}')::date END,ref_id)
   ON CONFLICT(salon_id,entity_id,parameter_id) DO UPDATE SET
     value_string=excluded.value_string,value_integer=excluded.value_integer,
     value_number=excluded.value_number,value_boolean=excluded.value_boolean,
     value_date=excluded.value_date,value_reference=excluded.value_reference;
  END IF;
 END LOOP;
 UPDATE __APP_SCHEMA__.entities SET version=version+1 WHERE salon_id=NEW.salon_id AND id=NEW.entity_id;
 RETURN NEW;
END $$;

