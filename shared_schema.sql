CREATE OR REPLACE FUNCTION __APP_SCHEMA__.guard_metadata() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
DECLARE old_row jsonb; new_row jsonb; type_id bigint; sid bigint; type_core boolean;
BEGIN
 IF TG_OP<>'INSERT' THEN
  old_row:=to_jsonb(OLD);
  IF TG_OP='UPDATE' AND pg_trigger_depth()>1 AND
      (to_jsonb(NEW)-'version')=(old_row-'version') THEN RETURN NEW; END IF;
  IF OLD.core THEN RAISE EXCEPTION 'Core metadata is immutable' USING ERRCODE='23514'; END IF;
 END IF;
 IF TG_OP<>'DELETE' THEN
  new_row:=to_jsonb(NEW);
  IF (NEW.core AND pg_trigger_depth()=1) OR (TG_OP='UPDATE' AND (NEW.id<>OLD.id OR NEW.salon_id<>OLD.salon_id
      OR NEW.code<>OLD.code)) THEN
   RAISE EXCEPTION 'Metadata identity/core flags are immutable' USING ERRCODE='23514';
  END IF;
  IF TG_OP='UPDATE' THEN NEW.version:=OLD.version+1; END IF;
 END IF;
 IF TG_TABLE_NAME='entity_parameters' THEN
  type_id:=COALESCE((new_row->>'entity_type_id')::bigint,(old_row->>'entity_type_id')::bigint);
  sid:=COALESCE((new_row->>'salon_id')::bigint,(old_row->>'salon_id')::bigint);
  SELECT core INTO STRICT type_core FROM __APP_SCHEMA__.entity_types WHERE salon_id=sid AND id=type_id FOR UPDATE;
  IF TG_OP<>'DELETE' AND type_core AND NEW.required AND NOT NEW.core THEN
   RAISE EXCEPTION 'Additional core parameters must be optional' USING ERRCODE='23514';
  END IF;
  IF TG_OP='UPDATE' AND NEW.entity_type_id<>OLD.entity_type_id THEN
   RAISE EXCEPTION 'Parameter ownership is immutable' USING ERRCODE='23514';
  END IF;
  IF TG_OP='DELETE' OR (TG_OP='UPDATE' AND
    (NEW.data_type<>OLD.data_type OR NEW.reference_type_id IS DISTINCT FROM OLD.reference_type_id)) THEN
   IF EXISTS(SELECT 1 FROM __APP_SCHEMA__.entity_parameter_values WHERE salon_id=sid AND parameter_id=OLD.id) THEN
    RAISE EXCEPTION 'Populated parameter cannot be removed or retyped' USING ERRCODE='23514';
   END IF;
  END IF;
  IF TG_OP<>'DELETE' AND NEW.required AND (TG_OP='INSERT' OR NOT OLD.required) AND EXISTS(
   SELECT 1 FROM __APP_SCHEMA__.entities e WHERE e.salon_id=sid AND e.entity_type_id=type_id AND NOT e.archived
    AND NOT EXISTS(SELECT 1 FROM __APP_SCHEMA__.entity_parameter_values v WHERE v.salon_id=sid
       AND v.entity_id=e.id AND v.parameter_id=NEW.id)) THEN
   RAISE EXCEPTION 'Required parameter needs a value on every existing entity' USING ERRCODE='23514';
  END IF;
  UPDATE __APP_SCHEMA__.entity_types SET version=version+1 WHERE salon_id=sid AND id=type_id;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION __APP_SCHEMA__.guard_entity() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
DECLARE typ __APP_SCHEMA__.entity_types;
BEGIN
 SELECT * INTO STRICT typ FROM __APP_SCHEMA__.entity_types WHERE salon_id=COALESCE(NEW.salon_id,OLD.salon_id)
   AND id=COALESCE(NEW.entity_type_id,OLD.entity_type_id) FOR UPDATE;
 IF pg_trigger_depth()=1 AND typ.core THEN
  RAISE EXCEPTION 'Core entities are changed by their service API' USING ERRCODE='23514';
 END IF;
 IF TG_OP='UPDATE' AND (NEW.id<>OLD.id OR NEW.salon_id<>OLD.salon_id
     OR NEW.entity_type_id<>OLD.entity_type_id OR NEW.projection_key IS DISTINCT FROM OLD.projection_key) THEN
  RAISE EXCEPTION 'Entity identity is immutable' USING ERRCODE='23514';
 END IF;
 IF TG_OP='UPDATE' AND NEW.archived AND NOT OLD.archived AND EXISTS(
  SELECT 1 FROM __APP_SCHEMA__.entity_parameter_values v JOIN __APP_SCHEMA__.entities e
   ON e.salon_id=v.salon_id AND e.id=v.entity_id
  WHERE v.salon_id=NEW.salon_id AND v.value_reference=NEW.id AND NOT e.archived) THEN
  RAISE EXCEPTION 'Entity is referenced by an active object' USING ERRCODE='23514';
 END IF;
 IF TG_OP<>'DELETE' AND NOT typ.core AND NEW.projection_key IS NOT NULL THEN
  RAISE EXCEPTION 'Custom entities cannot claim a core projection' USING ERRCODE='23514';
 END IF;
 IF TG_OP='UPDATE' THEN NEW.version:=OLD.version+1; END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION __APP_SCHEMA__.guard_entity_value() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
DECLARE p __APP_SCHEMA__.entity_parameters; e __APP_SCHEMA__.entities; ref_type bigint;
BEGIN
 SELECT * INTO STRICT p FROM __APP_SCHEMA__.entity_parameters
 WHERE salon_id=COALESCE(NEW.salon_id,OLD.salon_id) AND id=COALESCE(NEW.parameter_id,OLD.parameter_id) FOR SHARE;
 PERFORM 1 FROM __APP_SCHEMA__.entity_types WHERE salon_id=p.salon_id AND id=p.entity_type_id FOR UPDATE;
 IF pg_trigger_depth()=1 AND p.core AND NOT (
   TG_OP='UPDATE' AND p.code='name'
   AND COALESCE(current_setting('app.salon_profile_write',true),'')='on'
   AND __APP_SCHEMA__.current_salon_id()=p.salon_id
   AND EXISTS(SELECT 1 FROM __APP_SCHEMA__.entity_types
     WHERE salon_id=p.salon_id AND id=p.entity_type_id AND code='salon_settings')
 ) THEN
  RAISE EXCEPTION 'Core values are changed by their service API' USING ERRCODE='23514';
 END IF;
 IF TG_OP='DELETE' THEN
  -- A cascading delete runs after its parent entity has been removed.
  PERFORM 1 FROM __APP_SCHEMA__.entities WHERE salon_id=p.salon_id AND id=OLD.entity_id FOR UPDATE;
  RETURN OLD;
 END IF;
 SELECT * INTO STRICT e FROM __APP_SCHEMA__.entities WHERE salon_id=p.salon_id
   AND id=NEW.entity_id FOR UPDATE;
 IF TG_OP='UPDATE' AND (NEW.salon_id<>OLD.salon_id OR NEW.entity_id<>OLD.entity_id
    OR NEW.parameter_id<>OLD.parameter_id OR NEW.entity_type_id<>OLD.entity_type_id) THEN
  RAISE EXCEPTION 'Value identity is immutable' USING ERRCODE='23514';
 END IF;
 IF e.archived OR NEW.entity_type_id<>p.entity_type_id OR e.entity_type_id<>p.entity_type_id THEN
  RAISE EXCEPTION 'Invalid entity/parameter ownership' USING ERRCODE='23514';
 END IF;
 IF (p.data_type='string' AND NEW.value_string IS NULL)
 OR (p.data_type='integer' AND NEW.value_integer IS NULL)
 OR (p.data_type='number' AND NEW.value_number IS NULL)
 OR (p.data_type='boolean' AND NEW.value_boolean IS NULL)
 OR (p.data_type='date' AND NEW.value_date IS NULL)
 OR (p.data_type='reference' AND NEW.value_reference IS NULL) THEN
  RAISE EXCEPTION 'Value does not match parameter type' USING ERRCODE='23514';
 END IF;
 IF p.data_type='reference' THEN
  SELECT entity_type_id INTO ref_type FROM __APP_SCHEMA__.entities
    WHERE salon_id=NEW.salon_id AND id=NEW.value_reference AND NOT archived FOR SHARE;
  IF ref_type IS DISTINCT FROM p.reference_type_id THEN
   RAISE EXCEPTION 'Reference must point to an active entity of its declared type in the same salon'
    USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION __APP_SCHEMA__.check_required_entity_values() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
DECLARE eid bigint; sid bigint; typ bigint; previous_scope text;
BEGIN
 eid:=COALESCE((to_jsonb(NEW)->>'entity_id')::bigint,(to_jsonb(OLD)->>'entity_id')::bigint,
              (to_jsonb(NEW)->>'id')::bigint,(to_jsonb(OLD)->>'id')::bigint);
 sid:=COALESCE(NEW.salon_id,OLD.salon_id);
 previous_scope:=current_setting('app.salon_id',true);
 PERFORM set_config('app.salon_id',sid::text,true);
 SELECT entity_type_id INTO typ FROM __APP_SCHEMA__.entities WHERE salon_id=sid AND id=eid AND NOT archived;
 IF FOUND AND EXISTS(SELECT 1 FROM __APP_SCHEMA__.entity_parameters p WHERE p.salon_id=sid
  AND p.entity_type_id=typ AND p.required AND NOT EXISTS(
   SELECT 1 FROM __APP_SCHEMA__.entity_parameter_values v WHERE v.salon_id=sid
     AND v.entity_id=eid AND v.parameter_id=p.id)) THEN
  RAISE EXCEPTION 'Missing required entity parameter' USING ERRCODE='23514';
 END IF;
 PERFORM set_config('app.salon_id',COALESCE(previous_scope,''),true);
 RETURN NULL;
END $$;

-- Compatibility writes are commands: both projection and canonical values
-- change in the same transaction. Direct canonical core writes are rejected.
CREATE OR REPLACE FUNCTION __APP_SCHEMA__.projection_entity_before() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
DECLARE typ bigint; key jsonb := '{}'::jsonb; column_name text;
BEGIN
 IF TG_OP='UPDATE' THEN
  IF NEW.salon_id<>OLD.salon_id OR NEW.entity_id IS DISTINCT FROM OLD.entity_id THEN
   RAISE EXCEPTION 'Projection ownership is immutable' USING ERRCODE='23514';
  END IF;
  FOREACH column_name IN ARRAY string_to_array(TG_ARGV[1],',') LOOP
   IF to_jsonb(NEW)->column_name IS DISTINCT FROM to_jsonb(OLD)->column_name THEN
    RAISE EXCEPTION 'Projection identity is immutable' USING ERRCODE='23514';
   END IF;
  END LOOP;
  IF TG_TABLE_NAME='masters' AND (to_jsonb(NEW)->'shared_master_id') IS DISTINCT FROM (to_jsonb(OLD)->'shared_master_id') THEN
   RAISE EXCEPTION 'Shared master identity is immutable; attach a new salon profile' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
 END IF;
 SELECT id INTO STRICT typ FROM __APP_SCHEMA__.entity_types WHERE salon_id=NEW.salon_id AND code=TG_ARGV[0];
 FOREACH column_name IN ARRAY string_to_array(TG_ARGV[1],',') LOOP
  key:=key || jsonb_build_object(column_name,to_jsonb(NEW)->column_name);
 END LOOP;
 IF NEW.entity_id IS NOT NULL THEN
  RAISE EXCEPTION 'Projection entity identity is assigned internally' USING ERRCODE='23514';
 END IF;
 INSERT INTO __APP_SCHEMA__.entities(salon_id,entity_type_id,projection_key) VALUES(NEW.salon_id,typ,key)
 ON CONFLICT(salon_id,entity_type_id,projection_key) DO UPDATE
  SET projection_key=excluded.projection_key
 RETURNING id INTO NEW.entity_id;
 IF TG_TABLE_NAME='masters' AND (to_jsonb(NEW)->>'shared_master_id') IS NULL THEN
  INSERT INTO __APP_SCHEMA__.shared_masters DEFAULT VALUES RETURNING id INTO NEW.shared_master_id;
 END IF;
 RETURN NEW;
END $$;

-- BEFORE INSERT also runs for candidates rejected by ON CONFLICT. A natural
-- projection key reuses its entity above; a generated-ID candidate can instead
-- conflict on another unique key. Remove its still-empty entity after the
-- actual projection INSERT/UPDATE has completed, before deferred required-value
-- checks. Established projections and entities with values are never removed.
CREATE OR REPLACE FUNCTION __APP_SCHEMA__.prune_ignored_projection_entities() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
DECLARE sid bigint := __APP_SCHEMA__.current_salon_id(); typ bigint;
BEGIN
 IF sid IS NULL THEN RETURN NULL; END IF;
 SELECT id INTO STRICT typ FROM __APP_SCHEMA__.entity_types WHERE salon_id=sid AND code=TG_ARGV[0];
 EXECUTE format('DELETE FROM %I.entities e WHERE e.salon_id=$1 AND e.entity_type_id=$2
  AND NOT EXISTS(SELECT 1 FROM %I.%I p WHERE p.salon_id=e.salon_id AND p.entity_id=e.id)
  AND NOT EXISTS(SELECT 1 FROM %I.entity_parameter_values v WHERE v.salon_id=e.salon_id AND v.entity_id=e.id)',
  TG_TABLE_SCHEMA,TG_TABLE_SCHEMA,TG_TABLE_NAME,TG_TABLE_SCHEMA) USING sid,typ;
 RETURN NULL;
END $$;

