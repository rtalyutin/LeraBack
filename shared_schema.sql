 RETURN NULL;
END $$;

CREATE OR REPLACE FUNCTION __APP_SCHEMA__.guard_salon_registry() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
BEGIN
 IF NEW.id<>OLD.id THEN RAISE EXCEPTION 'Salon identity is immutable' USING ERRCODE='23514'; END IF;
 IF pg_trigger_depth()=1 AND
  (NEW.name IS DISTINCT FROM OLD.name OR NEW.entity_id IS DISTINCT FROM OLD.entity_id) THEN
  RAISE EXCEPTION 'Salon name/entity are canonical metadata projections' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION __APP_SCHEMA__.shared_master_conflict(local_master_id bigint,start_text text,end_text text,exclude_id bigint DEFAULT NULL)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
DECLARE shared_id bigint; sid bigint:=__APP_SCHEMA__.current_salon_id();
BEGIN
 IF sid IS NULL THEN RAISE EXCEPTION 'Salon context required' USING ERRCODE='42501'; END IF;
 SELECT shared_master_id INTO shared_id FROM __APP_SCHEMA__.masters WHERE salon_id=sid AND id=local_master_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Master not available in this salon' USING ERRCODE='42501'; END IF;
 IF exclude_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM __APP_SCHEMA__.bookings WHERE salon_id=sid AND id=exclude_id) THEN
  RAISE EXCEPTION 'Excluded booking not available in this salon' USING ERRCODE='42501';
 END IF;
 IF start_text::timestamptz>=end_text::timestamptz THEN
  RAISE EXCEPTION 'Invalid booking interval' USING ERRCODE='23514';
 END IF;
 RETURN EXISTS(SELECT 1 FROM __APP_SCHEMA__.shared_master_busy WHERE shared_master_id=shared_id
  AND booking_id IS DISTINCT FROM exclude_id
  AND start_utc<end_text::timestamptz AND end_utc>start_text::timestamptz);
END $$;

CREATE OR REPLACE FUNCTION __APP_SCHEMA__.protect_booking_overlap() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
DECLARE shared_id bigint;
BEGIN
 IF NEW.salon_id IS DISTINCT FROM __APP_SCHEMA__.current_salon_id() THEN
  RAISE EXCEPTION 'Salon context required' USING ERRCODE='42501';
 END IF;
 IF NEW.status='confirmed' THEN
  IF current_setting('transaction_isolation')<>'read committed' THEN
   RAISE EXCEPTION 'Confirmed bookings require READ COMMITTED isolation'
    USING ERRCODE='0A000';
  END IF;
  PERFORM pg_advisory_xact_lock(706547229101);
  SELECT shared_master_id INTO STRICT shared_id FROM __APP_SCHEMA__.masters WHERE salon_id=NEW.salon_id AND id=NEW.master_id;
  IF EXISTS(SELECT 1 FROM __APP_SCHEMA__.shared_master_busy WHERE shared_master_id=shared_id
   AND booking_id IS DISTINCT FROM NEW.id AND start_utc<NEW.end_utc::timestamptz AND end_utc>NEW.start_utc::timestamptz)
  OR EXISTS(SELECT 1 FROM __APP_SCHEMA__.bookings b WHERE b.salon_id=NEW.salon_id AND b.status='confirmed'
   AND b.id IS DISTINCT FROM NEW.id AND b.start_utc::timestamptz<NEW.end_utc::timestamptz
   AND b.end_utc::timestamptz>NEW.start_utc::timestamptz
   AND (b.room_id=NEW.room_id OR (NEW.client_id IS NOT NULL AND b.client_id=NEW.client_id)
       OR b.phone_snapshot=NEW.phone_snapshot)) THEN
   RAISE EXCEPTION 'booking overlap' USING ERRCODE='23505';
  END IF;
 END IF;
 RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION __APP_SCHEMA__.sync_shared_master_busy() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, __APP_SCHEMA__ AS $$
DECLARE shared_id bigint;
BEGIN
 IF TG_OP='DELETE' THEN DELETE FROM __APP_SCHEMA__.shared_master_busy WHERE booking_id=OLD.id; RETURN OLD; END IF;
 IF NEW.status<>'confirmed' THEN DELETE FROM __APP_SCHEMA__.shared_master_busy WHERE booking_id=NEW.id; RETURN NEW; END IF;
 SELECT shared_master_id INTO STRICT shared_id FROM __APP_SCHEMA__.masters WHERE salon_id=NEW.salon_id AND id=NEW.master_id;
 INSERT INTO __APP_SCHEMA__.shared_master_busy(booking_id,shared_master_id,start_utc,end_utc)
 VALUES(NEW.id,shared_id,NEW.start_utc::timestamptz,NEW.end_utc::timestamptz)
 ON CONFLICT(booking_id) DO UPDATE SET shared_master_id=excluded.shared_master_id,
  start_utc=excluded.start_utc,end_utc=excluded.end_utc;
 RETURN NEW;
END $$;
